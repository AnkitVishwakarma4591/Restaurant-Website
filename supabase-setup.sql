-- Run this in Supabase Dashboard > SQL Editor.
create table if not exists public.bookings (
  id bigint generated by default as identity primary key,
  name text not null,
  phone text not null,
  email text,
  date date not null,
  time text not null,
  guests text not null,
  occasion text,
  requests text,
  created_at timestamptz not null default now()
);

alter table public.bookings enable row level security;

-- Website visitors can submit bookings but cannot read existing customer data.
create policy "Allow booking submissions"
  on public.bookings
  for insert
  to anon
  with check (
    length(trim(name)) > 0
    and length(trim(phone)) > 0
    and length(trim(time)) > 0
    and length(trim(guests)) > 0
  );

grant insert on public.bookings to anon;
grant usage on sequence public.bookings_id_seq to anon;
